/**
 * Build pipeline for dsh-rich-msg.
 *
 * Produces the two halves the DSH plugin contract needs:
 *   lib/index.js   Node ESM plugin (tools + artifact store + optional route)
 *   lib/client.js  Browser bundle wrapped in the DSH module-loader protocol
 *                  (window.__ModuleLoader__.load({ id, factory(require) {...} }))
 *
 * Uses a locally installed esbuild (this project intentionally keeps no build
 * dependency of its own); set DSH_RICH_MSG_ESBUILD_DIR to override the search.
 * React stays external for the browser half: the DSH web shell supplies it from
 * its frozen platform module table. CSS files are compiled as text exports and
 * injected by the client plugin, because DSH loads one JS artifact and has no
 * CSS manifest channel.
 */
import { mkdir, readFile, writeFile, rm, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const outDir = path.join(root, 'lib');

/** Resolve the esbuild JS API from a local install. */
async function loadEsbuild() {
  const candidates = [
    process.env.DSH_RICH_MSG_ESBUILD_DIR,
    'E:/tools/esbuild',
    'E:/tools/esbuild/node_modules/esbuild',
    path.join(root, 'node_modules/esbuild')
  ].filter(Boolean);
  for (const base of candidates) {
    for (const rel of ['node_modules/esbuild/lib/main.js', 'lib/main.js']) {
      const entry = path.join(base, rel);
      if (!existsSync(entry)) continue;
      const mod = await import(pathToFileURL(entry).href);
      return mod.default ?? mod;
    }
  }
  throw new Error('esbuild not found; set DSH_RICH_MSG_ESBUILD_DIR to a directory containing node_modules/esbuild');
}

/** Compile stylesheets to plain string modules so one JS artifact carries the CSS. */
const cssTextPlugin = {
  name: 'css-text',
  setup(build) {
    build.onLoad({ filter: /\.css$/ }, async (args) => ({
      contents: 'export default ' + JSON.stringify(await readFile(args.path, 'utf8')) + ';',
      loader: 'js'
    }));
  }
};

/** Turn the CJS client body into the loader-style script the browser shell expects. */
function wrapClientBundle(pkgName, cjsBody) {
  return [
    '/* Generated by scripts/build.mjs - do not edit. */',
    'window.__ModuleLoader__.load({',
    '\tid: ' + JSON.stringify(pkgName) + ',',
    '\tfactory: (require) => {',
    '\t\tvar module = { exports: {} };',
    '\t\tvar exports = module.exports;',
    cjsBody.replace(/^"use strict";\s*/u, ''),
    '\t\treturn module.exports;',
    '\t}',
    '});',
    ''
  ].join('\n');
}

const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const pkgName = packageJson.name;
const esbuild = await loadEsbuild();
await mkdir(outDir, { recursive: true });

const shared = {
  bundle: true,
  logLevel: 'info',
  sourcemap: false,
  target: ['es2022'],
  legalComments: 'none',
  plugins: [cssTextPlugin]
};

const hostResult = await esbuild.build({
  ...shared,
  entryPoints: [path.join(root, 'src/host/index.ts')],
  outfile: path.join(outDir, 'index.js'),
  format: 'esm',
  platform: 'node',
  packages: 'bundle',
  banner: { js: '/* Generated by scripts/build.mjs - do not edit. */' }
});

const clientBody = path.join(outDir, '.client-body.js');
await esbuild.build({
  ...shared,
  entryPoints: [path.join(root, 'src/client/index.tsx')],
  outfile: clientBody,
  format: 'cjs',
  platform: 'browser',
  jsx: 'automatic',
  jsxImportSource: 'react',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  define: { 'process.env.NODE_ENV': '"production"' }
});
const body = await readFile(clientBody, 'utf8');
await writeFile(path.join(outDir, 'client.js'), wrapClientBundle(pkgName, body), 'utf8');
await rm(clientBody, { force: true });

const hostStat = await stat(path.join(outDir, 'index.js'));
const clientStat = await stat(path.join(outDir, 'client.js'));
console.log('built lib/index.js  (' + hostStat.size + ' bytes)');
console.log('built lib/client.js (' + clientStat.size + ' bytes)');
console.log('host esbuild warnings:', hostResult.warnings.length);
